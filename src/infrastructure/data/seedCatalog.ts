const createReviews = (tourId: string, offset: number): Review[] => {
  const reviewsCount = 2 + (offset % 3);
  const scoreProfiles =
    offset % 4 === 0 ? fourStarScoreProfiles : fiveStarScoreProfiles;

  return reviewers.slice(0, reviewsCount).map((reviewer, index) => {
    const scores = scoreProfiles[(offset + index) % scoreProfiles.length];

    return new Review(
      `review-${tourId}-${index + 1}`,
      reviewer.userId,
      tourId,
      reviewer.name,
      reviewer.role,
      reviewer.avatar,
      reviewMessages[(offset + index) % reviewMessages.length],
      { ...scores },
      seedDate,
      seedDate,
    );
  });
};

