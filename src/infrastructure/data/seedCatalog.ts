const createGallery = (cardImage: string, heroImage?: string): string[] => [
  heroImage ?? cardImage,
  cardImage,
  'https://images.unsplash.com/photo-1500375592092-40eb2168fd21?auto=format&fit=crop&w=900&q=80',
  'https://images.unsplash.com/photo-1500534314209-a25ddb2bd429?auto=format&fit=crop&w=900&q=80',
];

const buildTour = (record: TourSeedRecord, index: number): Tour => {
  const destination = destinations[record.destinationId];
  const kind = record.kind ?? 'standard';
  const amenityProfile =
    record.amenities ??
    [...amenityProfiles[kind === 'premium' ? 'premium' : kind === 'seasonal' ? 'seasonal' : kind === 'featured' ? 'featured' : 'standard']];

  const props = {
    id: record.id,
    title: record.title,
    slug: slugify(record.title),
    summary: record.summary,
    heroImage: record.heroImage ?? destination.getHeroImage(),
    cardImage: record.cardImage,
    gallery: record.gallery ?? createGallery(record.cardImage, record.heroImage),
    destination,
    basePrice: record.basePrice,
    locationNote: destination.getLabel(),
    durationDays: record.durationDays,
    transportMode:
      record.transportMode ?? destinationTransportProfiles[record.destinationId],
    groupSize: record.groupSize,
    typeLabel: record.typeLabel,
    languages: record.languages ?? destinationLanguageProfiles[record.destinationId],
    amenities: amenityProfile,
    highlightItems,
    includedItems,
    excludedItems,
    itinerary: createItinerary(destination.getCity()),
    reviews: createReviews(record.id, index),
    ribbonLabel: record.ribbonLabel ?? null,
    createdAt: seedDate,
    updatedAt: seedDate,
  };

  switch (record.kind) {
    case 'featured':
      return new FeaturedTour(props);
    case 'seasonal':
      return new SeasonalTour(
        props,
        record.seasonName ?? 'Seasonal',
        record.seasonMultiplier ?? 0.88,
      );
    case 'premium':
      return new PremiumTour(props, record.premiumMultiplier ?? 1.15);
    default:
      return new Tour(props);
  }
};

export const createSeedTours = (): Tour[] =>
  records.map((record, index) => buildTour(record, index));
